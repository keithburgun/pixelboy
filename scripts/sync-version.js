// Copies the version from package.json into app/js/version.js so the web build knows its version.
const fs = require('fs');
const path = require('path');
const pkg = require('../package.json');
const file = path.join(__dirname, '..', 'app', 'js', 'version.js');
fs.writeFileSync(file, `// Generated by scripts/sync-version.js — do not edit.\nwindow.PIXELBOY_VERSION = ${JSON.stringify(pkg.version)};\n`);
